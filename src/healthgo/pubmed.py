"""Quarterly research pull: what PubMed added since a sector's last review, as one markdown file per sector.

Plain HTTP and XML, no model in the loop, so the pull costs no tokens; a Sonnet agent screens the file afterwards
(/knowledge-review). Searches and dates live in config/research.json. NCBI E-utilities allow 3 requests/s without a
key and 10 with one; the key is in 1Password (`NCBI/API_key`) and the pull still works without it.
"""

from __future__ import annotations

import json
import time
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from datetime import date
from pathlib import Path

from . import config, vault

EUTILS = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils"
RESEARCH_FILE = config.ROOT / "config" / "research.json"
STUDY_FILTER = ("(meta-analysis[pt] OR systematic review[pt] OR randomized controlled trial[pt] "
                "OR meta-analysis[tiab] OR systematic review[tiab] OR randomized[tiab] OR randomised[tiab])")
TYPE_RANK = {"Meta-Analysis": 0, "Systematic Review": 1, "Randomized Controlled Trial": 2}


def research() -> dict:
    return json.loads(RESEARCH_FILE.read_text())


def quarter(d: date) -> str:
    return f"{d.year}-Q{(d.month - 1) // 3 + 1}"


class Client:
    def __init__(self) -> None:
        try:
            self.key = vault.read("NCBI/API_key").strip()
        except vault.VaultError:
            self.key = None
        self.pause = 0.12 if self.key else 0.4

    def get(self, tool: str, **params) -> bytes:
        if self.key:
            params["api_key"] = self.key
        url = f"{EUTILS}/{tool}.fcgi?{urllib.parse.urlencode(params)}"
        time.sleep(self.pause)
        with urllib.request.urlopen(url, timeout=60) as r:
            return r.read()


def search(client: Client, query: str, since: date, until: date, retmax: int) -> tuple[int, list[str]]:
    """PMIDs added to PubMed (Entrez date) between `since` and `until` matching `query` and the study-type filter."""
    raw = client.get("esearch", db="pubmed", term=f"({query}) AND {STUDY_FILTER}", retmode="json", retmax=retmax,
                     datetype="edat", mindate=since.strftime("%Y/%m/%d"), maxdate=until.strftime("%Y/%m/%d"))
    res = json.loads(raw)["esearchresult"]
    return int(res["count"]), res["idlist"]


def _text(el) -> str:
    return " ".join("".join(el.itertext()).split()) if el is not None else ""


def parse(xml: bytes) -> list[dict]:
    out = []
    for art in ET.fromstring(xml).iter("PubmedArticle"):
        # the article's own ids only; iter() would also walk the ReferenceList and pick up a cited paper's PMC id
        ids = {i.get("IdType"): i.text for i in art.findall("PubmedData/ArticleIdList/ArticleId")}
        parts = []
        for a in art.iter("AbstractText"):
            label = a.get("Label")
            parts.append(f"**{label.title()}:** {_text(a)}" if label else _text(a))
        year = art.findtext(".//JournalIssue/PubDate/Year") or art.findtext(".//JournalIssue/PubDate/MedlineDate") or ""
        out.append({
            "pmid": art.findtext(".//PMID"),
            "title": _text(art.find(".//ArticleTitle")),
            "journal": art.findtext(".//Journal/ISOAbbreviation") or art.findtext(".//Journal/Title") or "",
            "year": year[:4],
            "types": [_text(t) for t in art.iter("PublicationType")],
            "pmcid": ids.get("pmc"),
            "doi": ids.get("doi"),
            "abstract": "\n\n".join(parts),
        })
    return out


def fetch(client: Client, pmids: list[str]) -> list[dict]:
    out = []
    for i in range(0, len(pmids), 100):
        out += parse(client.get("efetch", db="pubmed", id=",".join(pmids[i:i + 100]), retmode="xml"))
    return out


def _rank(p: dict) -> int:
    return min((TYPE_RANK[t] for t in p["types"] if t in TYPE_RANK), default=3)


def _short_type(p: dict) -> str:
    return {0: "MA", 1: "SR", 2: "RCT"}.get(_rank(p), "other")


def render(sector: str, since: date, until: date, hits: list[dict], papers: list[dict]) -> str:
    lines = [f"# PubMed pull: {sector}, {since} → {until}", "",
             ("Added to PubMed in this window, filtered to meta-analyses, systematic reviews and RCTs. Generated by "
              "`healthgo pubmed`; screened by /knowledge-review. Not committed."), "", "## Searches", "",
             "| # | Hits | Fetched | Query |", "|---|---|---|---|"]
    for i, h in enumerate(hits, 1):
        more = " ⚠️ truncated" if h["count"] > len(h["pmids"]) else ""
        lines.append(f"| {i} | {h['count']} | {len(h['pmids'])}{more} | `{h['query']}` |")
    newest_first = sorted(papers, key=lambda p: p["year"], reverse=True)
    ordered = sorted(newest_first, key=_rank)
    # Screen from the index, then open only the abstracts that matter (grep "### PMID <id>"): saves most of the tokens.
    lines += ["", f"## Index ({len(papers)} papers, meta-analyses first)", ""]
    lines += [f"- {p['pmid']} · {_short_type(p)} · {p['year']} · {p['title']}" for p in ordered]
    lines += ["", "## Abstracts", ""]
    for p in ordered:
        links = [f"https://pubmed.ncbi.nlm.nih.gov/{p['pmid']}/"]
        if p["pmcid"]:
            links.append(f"full text https://pmc.ncbi.nlm.nih.gov/articles/{p['pmcid']}/")
        elif p["doi"]:
            links.append(f"doi {p['doi']}")
        types = ", ".join(t for t in p["types"] if t != "Journal Article") or "Journal Article"
        lines += [f"### PMID {p['pmid']} · {p['title']}", "",
                  f"{p['journal']} {p['year']} · {types} · queries {', '.join(map(str, p['queries']))}", "",
                  " · ".join(links), "", p["abstract"] or "_No abstract._", ""]
    return "\n".join(lines)


def pull(sector: str, since: date | None = None, until: date | None = None, out: Path | None = None) -> dict:
    cfg = research()
    sec = cfg["sectors"][sector]
    since = since or date.fromisoformat(sec["last_reviewed"])
    until = until or config.today()
    out = out or config.ROOT / "research" / sector / "reviews" / f"{quarter(until)}-pulled.md"
    client = Client()

    hits, by_pmid = [], {}
    for i, q in enumerate(sec["queries"], 1):
        count, pmids = search(client, q, since, until, cfg.get("per_query_max", 60))
        hits.append({"query": q, "count": count, "pmids": pmids})
        for pmid in pmids:
            by_pmid.setdefault(pmid, []).append(i)
    papers = fetch(client, list(by_pmid)) if by_pmid else []
    for p in papers:
        p["queries"] = by_pmid.get(p["pmid"], [])

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(sector, since, until, hits, papers))
    return {"sector": sector, "since": since.isoformat(), "until": until.isoformat(), "papers": len(papers),
            "truncated_queries": [i for i, h in enumerate(hits, 1) if h["count"] > len(h["pmids"])],
            "api_key": bool(client.key),
            "file": str(out.relative_to(config.ROOT) if out.is_relative_to(config.ROOT) else out)}
